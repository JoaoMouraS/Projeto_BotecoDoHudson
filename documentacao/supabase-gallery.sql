-- Execute este script no SQL Editor do projeto Supabase.
-- Depois crie um bucket publico chamado: gallery

insert into storage.buckets (id, name, public)
values
  ('gallery', 'gallery', true),
  ('event-images', 'event-images', true),
  ('profile-images', 'profile-images', true)
on conflict (id) do update set public = excluded.public;

create table if not exists public.gallery_photos (
  id bigint generated by default as identity primary key,
  title text,
  event text not null,
  event_date date,
  storage_path text not null unique,
  published boolean not null default true,
  created_at timestamptz not null default now()
);

alter table public.gallery_photos enable row level security;

drop policy if exists "Fotos publicadas podem ser lidas" on public.gallery_photos;
create policy "Fotos publicadas podem ser lidas"
on public.gallery_photos
for select
using (published = true);

-- Leitura publica dos tres buckets usados pelo frontend.
drop policy if exists "Imagens publicas podem ser lidas" on storage.objects;
create policy "Imagens publicas podem ser lidas"
on storage.objects
for select
using (bucket_id in ('gallery', 'event-images', 'profile-images'));

-- O frontend usa a publishable key para enviar imagens. Como o login atual
-- usa JWT proprio do Spring (e nao Supabase Auth), o Storage nao consegue
-- identificar o usuario. Restrinja tipos/tamanho no painel e migre depois
-- para URLs assinadas se o upload publico nao for aceitavel.
drop policy if exists "Uploads de imagens do site" on storage.objects;
create policy "Uploads de imagens do site"
on storage.objects
for insert
with check (bucket_id in ('event-images', 'profile-images'));

